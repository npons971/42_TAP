import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

// Exercise the shipped Svelte handlers, including empty arrays and asynchronous events.
const source = fs.readFileSync(new URL('../Project/client-gui/frontend/src/App.svelte', import.meta.url), 'utf8');
const script = source.split('<script>')[1].split('</script>')[0].replace(/import\s*\{[^}]*\}\s*from\s*['"]svelte['"];?/, '');
const sent = [];
const backend = {SendCommand: async command => sent.push(command), Disconnect: async () => sent.push('disconnect')};
const context = vm.createContext({console, setTimeout, onMount: () => {}, tick: async () => {}, window: {go: {main: {App: backend}}}});
vm.runInContext(script, context);
const run = code => vm.runInContext(code, context);
run(`handleServerOK('players=3', 'WHO')`);
assert.equal(run('serverPlayersCount'), 3);
assert.equal(run('currentRoom.id'), 'loc.town_square');
run(`handleServerOK('{"room":["alice"],"server":5}', 'WHO')`);
assert.equal(run('serverPlayersCount'), 5);
assert.equal(run('currentRoom.id'), 'loc.town_square');
run(`handleServerOK('["item.apple"]', 'INVENTORY')`);
run(`handleServerOK('[]', 'QUESTS')`);
assert.equal(run('inventory[0].id'), 'item.apple');
assert.equal(run('quests.length'), 0);
run(`handleServerOK('[{"quest_id":"quest.herbal_cure","status":"active","progress":"1/1"}]', 'QUESTS')`);
assert.equal(run('quests[0].id'), 'quest.herbal_cure');
run(`handleServerOK('[]', 'INVENTORY')`);
assert.equal(run('inventory.length'), 0);
assert.equal(run('quests.length'), 1);
run(`handleServerOK('{"hp":80,"max_hp":100,"status":"combat"}', 'STATUS')`);
assert.equal(run('playerHP'), 80);
assert.equal(run('combatState'), 'EN_COMBAT');
run(`handleServerEVT('STATS players=2')`);
assert.equal(run('serverPlayersCount'), 2);
run(`handleServerEVT('GROUP INVITE alice')`);
assert.match(run('messages.group.at(-1).text'), /INVITE: alice/);
run(`handleServerOK('Hello traveler!', 'TALK')`);
assert.equal(run('activeDialogue.text'), 'Hello traveler!');
run(`handleServerERR('400 INVALID_ARGUMENTS LOOK takes no arguments', 'LOOK', 'LOOK DETAILS')`);
run(`handleServerERR('400 UNKNOWN_COMMAND Unknown command', 'TALKJSON', 'TALKJSON Village Guard')`);
assert.deepEqual(sent.slice(0, 2), ['LOOK', 'TALK Village Guard']);
run(`connecting = true; handleServerERR('201 NAME_IN_USE Already connected', 'CONNECT')`);
assert.equal(run('connecting'), false);
assert.equal(sent.at(-1), 'disconnect');
console.log('GUI protocol: WHO, empty lists, quest IDs, STATS/GROUP, TALK, extension fallback and CONNECT errors passed.');
